WEEKDAYS = ["понедельник", "вторник", "среда", "четверг",
            "пятница", "суббота", "воскресенье"]


def _date_hints():
    """Готовые ориентиры дат.

    Модели плохо считают относительные сроки: «до конца недели» она может
    понять как конец следующей. Дешевле посчитать за неё и передать готовым.
    """
    today = dt.date.today()

    def fmt(d):
        return f"{d.strftime('%d.%m.%Y')}, {WEEKDAYS[d.weekday()]}"

    friday = today + dt.timedelta(days=(4 - today.weekday()) % 7)
    monday = today + dt.timedelta(days=(7 - today.weekday()) % 7 or 7)

    return "\n".join([
        f"- сегодня: {fmt(today)}",
        f"- «до конца недели», «на этой неделе» — по {fmt(friday)}",
        f"- «в понедельник», «на следующей неделе» — с {fmt(monday)}",
        f"- «завтра» — {fmt(today + dt.timedelta(days=1))}",
        "- если названо только число месяца без года — имеется в виду "
        f"ближайшая такая дата начиная с {today.strftime('%d.%m.%Y')}",
    ])


def _client():
    return OpenAI(api_key=config.LLM_API_KEY, base_url=config.LLM_BASE_URL)


def system_message():
    return {"role": "system", "content": SYSTEM_PROMPT.format(dates=_date_hints())}


def _complete(client, history, on_wait=None):
    """Запрос к модели с повтором при исчерпании квоты.

    Бесплатный тариф Gemini — 5 запросов в минуту, а один ход диалога
    с вызовом инструмента расходует два. Провайдер сам сообщает, сколько
    ждать, поэтому берём задержку из текста ошибки.
    """
    for attempt in range(MAX_RETRIES):
        try:
            return client.chat.completions.create(
                model=config.LLM_MODEL,
                messages=[system_message()] + history,
                tools=tools.TOOLS,
            )
        except RateLimitError as e:
            if attempt == MAX_RETRIES - 1:
                raise
            match = re.search(r"retry in ([\d.]+)s", str(e))
            delay = float(match.group(1)) + 1 if match else 20 * (attempt + 1)
            if on_wait:
                on_wait(delay)
            time.sleep(delay)


def run(messages, on_tool_call=None, on_wait=None):
    """Прогоняет один ход диалога.

    messages — история без системного сообщения, оно добавляется само.
    on_tool_call — колбэк (имя, аргументы, результат) для показа в интерфейсе.
    on_wait — колбэк (секунды) при ожидании из-за лимита запросов.
    Возвращает обновлённую историю; последний элемент — ответ ассистента.
    """
    client = _client()
    history = list(messages)
    corrections_left = 1

    for _ in range(MAX_STEPS):
        response = _complete(client, history, on_wait)
        message = response.choices[0].message

        # Сообщение кладём в историю целиком, а не пересобираем по полям.
        # Gemini 3 подписывает свои рассуждения и возвращает подпись в
        # нестандартном поле tool_calls[N].extra_content.google.thought_signature.
        # Если её потерять, следующий запрос упадёт с 400. model_dump()
        # сохраняет такие поля, ручная сборка — нет.
        history.append(message.model_dump(exclude_none=True))

        if not message.tool_calls:
            # Ответ готов — сверяем упомянутые номера с реестром, пока
            # человек его не увидел.
            unknown = grounding.find_unknown(message.content)
            if unknown and corrections_left:
                corrections_left -= 1
                if on_tool_call:
                    on_tool_call("grounding_check", {"unknown": unknown},
                                 {"result": "ответ отправлен на исправление"})
                history.append(grounding.correction_message(unknown))
                continue
            return history

        for call in message.tool_calls:
            name = call.function.name
            try:
                args = json.loads(call.function.arguments or "{}")
                handler = tools.HANDLERS[name]
                result = handler(**args)
            except Exception as e:
                result = {"error": f"{type(e).__name__}: {e}"}

            if on_tool_call:
                on_tool_call(name, args if isinstance(args, dict) else {}, result)

            history.append({
                "role": "tool",
                "tool_call_id": call.id,
                "content": json.dumps(result, ensure_ascii=False, default=str),
            })

    history.append({
        "role": "assistant",
        "content": "Не удалось завершить за отведённое число шагов. "
                   "Попробуйте сформулировать задачу проще.",
    })
    return history


def last_reply(history):
    """Текст последнего ответа ассистента. content может отсутствовать."""
    for message in reversed(history):
        if message.get("role") == "assistant" and message.get("content"):
            return message["content"]
    return "(пустой ответ)"
